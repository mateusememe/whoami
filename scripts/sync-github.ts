// Fetches public facts about the repositories the portfolio links to and
// writes two snapshots, committed with the code:
//
// - src/data/github-stars.ts: stars per repository (small; the home page
//   shows them, so it is in the main bundle);
// - src/data/github-repos.ts: last push and bytes per language (the
//   project pages show them; it loads with that chunk).
//
// TypeScript modules rather than JSON, so every loader (Vite, tsx,
// Playwright) imports them the same way.
//
// The browser never calls the GitHub API. The deploy workflow runs this
// before the build (and once a week), so the published numbers stay
// current; locally, `npm run github:sync` refreshes the snapshot.
//
// Token: GITHUB_TOKEN, else `gh auth token`, else anonymous (60 requests an
// hour, enough for one run). On any failure the snapshot stays as it was.

import { execSync } from "child_process";
import { existsSync, readFileSync, writeFileSync } from "fs";
import { resolve } from "path";
import { contributions, projects } from "../src/data/portfolio";

const STARS_FILE = resolve("src/data/github-stars.ts");
const REPOS_FILE = resolve("src/data/github-repos.ts");

const HEADER = "// Generated by scripts/sync-github.ts (npm run github:sync). Do not edit.\n";

function module(name: string, type: string, value: unknown): string {
  return `${HEADER}\nexport const ${name}: ${type} = ${JSON.stringify(value, null, 2)};\n`;
}

function token(): string | undefined {
  if (process.env.GITHUB_TOKEN) return process.env.GITHUB_TOKEN;
  try {
    return execSync("gh auth token", { stdio: ["ignore", "pipe", "ignore"] }).toString().trim() || undefined;
  } catch {
    return undefined;
  }
}

/** `owner/name` from a GitHub URL, or null for anything else. */
export function repoOf(url: string | undefined): string | null {
  const match = url?.match(/^https:\/\/github\.com\/([^/]+)\/([^/?#]+)/);
  return match ? `${match[1]}/${match[2]}` : null;
}

const repos = [
  ...new Set([
    ...projects.map((project) => repoOf(project.githubUrl)).filter((repo): repo is string => !!repo),
    ...contributions.map((item) => item.repo),
  ]),
].sort();

const headers: Record<string, string> = {
  Accept: "application/vnd.github+json",
  "X-GitHub-Api-Version": "2022-11-28",
  "User-Agent": "whoami-portfolio-sync",
};
const auth = token();
if (auth) headers.Authorization = `Bearer ${auth}`;

async function get<T>(path: string): Promise<T> {
  const response = await fetch(`https://api.github.com${path}`, { headers });
  if (!response.ok) throw new Error(`${path}: HTTP ${response.status}`);
  return (await response.json()) as T;
}

try {
  const stars: Record<string, number> = {};
  const details: Record<string, { pushedAt: string; languages: Record<string, number> }> = {};
  for (const repo of repos) {
    const info = await get<{ stargazers_count: number; pushed_at: string }>(`/repos/${repo}`);
    const languages = await get<Record<string, number>>(`/repos/${repo}/languages`);
    stars[repo] = info.stargazers_count;
    details[repo] = { pushedAt: info.pushed_at.slice(0, 10), languages };
  }
  writeFileSync(STARS_FILE, module("githubStars", "Record<string, number>", stars));
  const next = module("githubRepos", "Record<string, { pushedAt: string; languages: Record<string, number> }>", details);
  if (!existsSync(REPOS_FILE) || readFileSync(REPOS_FILE, "utf8") !== next) writeFileSync(REPOS_FILE, next);
  const total = Object.values(stars).reduce((sum, count) => sum + count, 0);
  console.log(`✓ GitHub snapshot: ${repos.length} repositories, ${total} stars${auth ? "" : " (anonymous)"}`);
} catch (error) {
  console.warn(`⚠ sync-github: ${(error as Error).message}; the snapshot stays as it was`);
}
