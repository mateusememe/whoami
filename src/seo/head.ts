/**
 * Everything in <head> that describes a page to search engines, social
 * previews and agents, for one language. `scripts/generate-head.ts` writes
 * the English home block into index.html; `scripts/prerender.ts` swaps in
 * the right block for every other page and language.
 */
import { profile, socialLinks } from "@/data/portfolio";
import { HAS_NOTES, HOME, HTML_LANG, LANGUAGES, pagePath, type Page } from "@/i18n/routes";
import { type Language } from "@/i18n/translations";
import { buildJsonLd } from "@/seo/jsonld";
import { OG_IMAGE_FILES, PROFILE_FILES, RESUME_FILES } from "@/seo/files";
import { pageMeta, tr } from "@/seo/meta";
import { siteHref } from "@/seo/site";
import { FEED_FILES } from "@/seo/feed";

export const HEAD_START = "<!-- seo:start (generated by scripts/generate-head.ts, do not edit) -->";
export const HEAD_END = "<!-- seo:end -->";

const OG_LOCALE: Record<Language, string> = { en: "en_US", pt: "pt_BR", es: "es_ES" };

const escape = (value: string) =>
  value.replace(/&/g, "&amp;").replace(/"/g, "&quot;").replace(/</g, "&lt;").replace(/>/g, "&gt;");

export function renderHead(language: Language, siteUrl: string, target: Page = HOME): string {
  const { title, description, path } = pageMeta(target, language);
  const page = siteHref(siteUrl, path);
  const image = siteHref(siteUrl, OG_IMAGE_FILES[language]);
  const isHome = target.kind === "home";
  const imageAlt = tr(language, "seo.imageAlt");
  const twitter = socialLinks.find((link) => link.iconName === "X")?.displayText;

  const meta = (name: string, content: string) => `<meta name="${name}" content="${escape(content)}" />`;
  const property = (name: string, content: string) => `<meta property="${name}" content="${escape(content)}" />`;
  const link = (attributes: Record<string, string>) =>
    `<link ${Object.entries(attributes)
      .map(([key, value]) => `${key}="${escape(value)}"`)
      .join(" ")} />`;

  const lines = [
    `<title>${escape(title)}</title>`,
    meta("description", description),
    meta("author", profile.name),
    meta("robots", "index, follow, max-image-preview:large, max-snippet:-1"),
    link({ rel: "canonical", href: page }),
    "",
    "<!-- One URL per language -->",
    ...LANGUAGES.map((code) => link({ rel: "alternate", hreflang: HTML_LANG[code], href: siteHref(siteUrl, pagePath(code, target)) })),
    link({ rel: "alternate", hreflang: "x-default", href: siteHref(siteUrl, pagePath("en", target)) }),
    "",
    "<!-- Agent and crawler discovery (https://llmstxt.org) -->",
    link({ rel: "describedby", type: "text/plain", href: siteHref(siteUrl, "llms.txt"), title: "llms.txt" }),
    link({
      rel: "alternate",
      type: "text/markdown",
      href: siteHref(siteUrl, PROFILE_FILES[language]),
      title: "Profile (Markdown)",
    }),
    link({
      rel: "alternate",
      type: "application/json",
      href: siteHref(siteUrl, RESUME_FILES[language]),
      title: "Profile (JSON Resume)",
    }),
    link({ rel: "sitemap", type: "application/xml", href: siteHref(siteUrl, "sitemap.xml") }),
    ...(HAS_NOTES
      ? [link({ rel: "alternate", type: "application/atom+xml", href: siteHref(siteUrl, FEED_FILES[language]), title: tr(language, "seo.notesTitle") })]
      : []),
    "",
    "<!-- Identity: the same person on other sites -->",
    ...socialLinks.filter((item) => !item.href.startsWith("mailto:")).map((item) => link({ rel: "me", href: item.href })),
    "",
    property("og:type", isHome ? "profile" : "website"),
    property("og:site_name", profile.name),
    property("og:title", title),
    property("og:description", description),
    property("og:url", page),
    property("og:image", image),
    property("og:image:type", "image/png"),
    property("og:image:width", "1200"),
    property("og:image:height", "630"),
    property("og:image:alt", imageAlt),
    property("og:locale", OG_LOCALE[language]),
    ...LANGUAGES.filter((code) => code !== language).map((code) => property("og:locale:alternate", OG_LOCALE[code])),
    ...(isHome
      ? [
          property("profile:first_name", profile.givenName),
          property("profile:last_name", profile.familyName),
          property("profile:username", profile.githubUser),
        ]
      : []),
    "",
    meta("twitter:card", "summary_large_image"),
    ...(twitter ? [meta("twitter:site", twitter), meta("twitter:creator", twitter)] : []),
    meta("twitter:title", title),
    meta("twitter:description", description),
    meta("twitter:image", image),
    meta("twitter:image:alt", imageAlt),
    "",
    `<meta name="theme-color" content="#141414" media="(prefers-color-scheme: dark)" />`,
    `<meta name="theme-color" content="#f0f0f0" media="(prefers-color-scheme: light)" />`,
    meta("color-scheme", "dark light"),
    "",
    // "<" is escaped so the JSON can never close the script element early.
    `<script type="application/ld+json">${JSON.stringify(buildJsonLd(language, siteUrl, target)).replace(/</g, "\\u003c")}</script>`,
  ];

  return lines.map((line) => (line ? `    ${line}` : "")).join("\n");
}

/** Replaces the generated block of an HTML document. Throws if the markers are missing. */
export function replaceHead(html: string, block: string): string {
  const start = html.indexOf(HEAD_START);
  const end = html.indexOf(HEAD_END);
  if (start === -1 || end === -1) throw new Error("SEO head markers not found in the HTML");
  return `${html.slice(0, start)}${HEAD_START}\n${block}\n    ${html.slice(end)}`;
}
